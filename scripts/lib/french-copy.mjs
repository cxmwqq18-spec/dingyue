function protect(value) {
  const protectedValues = [];
  const next = value.replace(/https?:\/\/[^\s<>"']+|mailto:[^\s<>"']+|\{[A-Z0-9_:-]+\}|<[^>]+>|\/[A-Za-z0-9_./?=&%-]+/gi, (match) => {
    const token = `-FR_PROTECTED_${protectedValues.length}-`;
    protectedValues.push([token, match]);
    return token;
  });
  return { next, protectedValues };
}

function phrasePattern(from) {
  const escaped = from.replace(/[.*+?^${}()|[\[\]\\]/g, "\\$&");
  const prefix = /^[A-Za-zÀ-ÖØ-öø-ÿ]/.test(from) ? "\\b" : "";
  const suffix = /[A-Za-zÀ-ÖØ-öø-ÿ]$/.test(from) ? "\\b" : "";
  return new RegExp(`${prefix}${escaped}${suffix}`, "gi");
}

function replacePhrase(value, from, to) {
  return value.replace(phrasePattern(from), to);
}

function replaceProtectedPhrase(value, from, to, protectedValues) {
  return value.replace(phrasePattern(from), () => {
    const token = `-FR_PHRASE_${protectedValues.length}-`;
    protectedValues.push([token, to]);
    return token;
  });
}

export function translateFrenchText(value) {
  if (typeof value !== "string" || !value.trim()) return value;
  if (/^(?:https?:|\/assets\/|site_|prod_|price_|page_|media_|tool_|pack_|video_|ai_)/i.test(value.trim())) return value;
  const { next: protectedText, protectedValues } = protect(value);
  let translated = protectedText;
  for (const [from, to] of [...SPANISH_PHRASES].sort((left, right) => right[0].length - left[0].length)) {
    translated = replacePhrase(translated, from, to);
  }
  translated = translated.replace(/\b[A-Za-zÁÉÍÓÚáéíóúÑñ]+\b/g, (word) => SPANISH_WORDS.get(word.toLowerCase()) ?? word);
  for (const [from, to] of [...PHRASES].sort((left, right) => right[0].length - left[0].length)) {
    translated = replaceProtectedPhrase(translated, from, to, protectedValues);
  }
  translated = translated.replace(/\b[A-Za-z][A-Za-z'-]*\b/g, (word) => WORDS.get(word.toLowerCase()) ?? word);
  for (const [token, original] of protectedValues) translated = translated.replaceAll(token, original);
  return translated;
}
