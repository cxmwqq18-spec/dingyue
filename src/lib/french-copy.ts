const PROTECTED_VALUE_PATTERN = /^(?:https?:|mailto:|\/|\{[A-Z0-9_:-]+\})/i;
const EMBEDDED_PROTECTED_VALUE_PATTERN = /https?:\/\/[^\s<>"']+|mailto:[^\s<>"']+|\{[A-Z0-9_:-]+\}|<[^>]+>|\/[A-Za-z0-9_./?=&%-]+/gi;

function protectEmbeddedValues(value: string): { value: string; protectedValues: Array<readonly [string, string]> } {
  const protectedValues: Array<readonly [string, string]> = [];
  const next = value.replace(EMBEDDED_PROTECTED_VALUE_PATTERN, (match) => {
    const token = `-FR_VALUE_${protectedValues.length}-`;
    protectedValues.push([token, match]);
    return token;
  });
  return { value: next, protectedValues };
}

function phrasePattern(from: string): RegExp {
  const escaped = from.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
  const prefix = /^[A-Za-zÀ-ÖØ-öø-ÿ]/.test(from) ? "\\b" : "";
  const suffix = /[A-Za-zÀ-ÖØ-öø-ÿ]$/.test(from) ? "\\b" : "";
  return new RegExp(`${prefix}${escaped}${suffix}`, "gi");
}

function replaceFrenchPhrases(value: string): { value: string; protectedValues: Array<readonly [string, string]> } {
  const protectedValues: Array<readonly [string, string]> = [];
  let translated = value;
  for (const [from, to] of [...FRENCH_PHRASES].sort((left, right) => right[0].length - left[0].length)) {
    translated = translated.replace(phrasePattern(from), () => {
      const token = `-FR_PHRASE_${protectedValues.length}-`;
      protectedValues.push([token, to]);
      return token;
    });
  }
  return { value: translated, protectedValues };
}

export function frenchCopy(value: string): string {
  if (Object.prototype.hasOwnProperty.call(FRENCH_COPY, value)) return FRENCH_COPY[value];
  if (!value.trim() || PROTECTED_VALUE_PATTERN.test(value.trim())) return value;
  const protectedValueResult = protectEmbeddedValues(value);
  const phraseResult = replaceFrenchPhrases(protectedValueResult.value);
  let translated = phraseResult.value;
  translated = translated.replace(/\b[A-Za-z][A-Za-z'-]*\b/g, (word) => FRENCH_WORDS[word.toLowerCase()] ?? word);
  translated = translated
    .replace(/\bUploading\b/gi, "Importation en cours")
    .replace(/\bUpload\b/gi, "Importer")
    .replace(/\bDownload\b/gi, "Télécharger");
  for (const [token, replacement] of phraseResult.protectedValues) translated = translated.replaceAll(token, replacement);
  for (const [token, replacement] of protectedValueResult.protectedValues) translated = translated.replaceAll(token, replacement);
  return translated;
}
